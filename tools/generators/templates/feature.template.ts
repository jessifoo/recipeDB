// Helper functions
function capitalize(str: string): string {
  return str.charAt(0).toUpperCase() + str.slice(1);
}

function getZodType(type: string): string {
  const typeMap: Record<string, string> = {
    string: 'z.string()',
    number: 'z.number()',
    boolean: 'z.boolean()',
    date: 'z.date()',
    email: 'common.email',
    url: 'common.url',
  };
  return typeMap[type] || 'z.string()';
}
