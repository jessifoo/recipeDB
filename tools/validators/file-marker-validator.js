#!/usr/bin/env node

/**
 * File Marker Validator
 * Ensures all TypeScript files are created via generators
 * Rejects manual file creation
 */

const fs = require('fs');
const { execSync } = require('child_process');

const ALLOWED_MANUAL_FILES = [
  'README.md',
  '.gitignore',
  'package.json',
  'tsconfig.json',
  'biome.json',
  'nx.json',
  'jest.config.ts',
  'jest.preset.js',
  'playwright.config.ts',
  '.eslintrc.json',
  'eslint.config.mjs',
  'next.config.js',
  'tailwind.config.ts',
  'postcss.config.js',
];

const MARKER_PATTERN = /export const __metadata.*Symbol\.for\(['"]@app\/generated['"]\)/s;
const GENERATED_COMMENT = /@generated by @app\/generators/;

function getStagedFiles() {
  try {
    const output = execSync('git diff --cached --name-only --diff-filter=A', {
      encoding: 'utf-8',
    });
    return output
      .trim()
      .split('\n')
      .filter((f) => f.match(/\.(ts|tsx)$/) && !f.includes('node_modules'));
  } catch (e) {
    return [];
  }
}

function validateFile(filePath) {
  const fileName = filePath.split('/').pop();
  
  // Allow specific manual files
  if (ALLOWED_MANUAL_FILES.includes(fileName)) {
    return { valid: true };
  }
  
  // Allow test files (they're generated with implementation)
  if (fileName.endsWith('.test.ts') || fileName.endsWith('.test.tsx')) {
    return { valid: true };
  }
  
  // Allow config files
  if (fileName.endsWith('.config.ts') || fileName.endsWith('.config.js')) {
    return { valid: true };
  }
  
  // Read file content
  let content;
  try {
    content = fs.readFileSync(filePath, 'utf-8');
  } catch (e) {
    return { valid: true }; // File doesn't exist yet
  }
  
  // Check for generator marker
  if (!MARKER_PATTERN.test(content)) {
    return {
      valid: false,
      error: 'Missing generator marker. Use: npx nx g @app/generators:...',
    };
  }
  
  // Check for @generated comment
  if (!GENERATED_COMMENT.test(content)) {
    return {
      valid: false,
      error: 'Missing @generated comment',
    };
  }
  
  return { valid: true };
}

// Main execution
const stagedFiles = getStagedFiles();

if (stagedFiles.length === 0) {
  process.exit(0);
}

const violations = [];

for (const file of stagedFiles) {
  const result = validateFile(file);
  if (!result.valid) {
    violations.push({ file, error: result.error });
  }
}

if (violations.length > 0) {
  console.error('\n❌ MANUAL FILE CREATION DETECTED\n');
  console.error('All files must be created using generators:\n');

  violations.forEach(({ file, error }) => {
    console.error(`  ${file}`);
    console.error(`    → ${error}\n`);
  });

  console.error('Available generators:');
  console.error('  npx nx g @app/generators:module <name>');
  console.error('  npx nx g @app/generators:component <name>');
  console.error('  npx nx g @app/generators:api-route <name>\n');

  process.exit(1);
}

console.log('✅ File marker validation passed');
